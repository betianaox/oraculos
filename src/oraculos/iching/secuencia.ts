const claveDe = (l: LineasHexagrama | number[]) => l.join('');

const POR_PATRON: Record<string, number> = {};
SECUENCIA_KING_WEN.forEach((l, i) => {
  POR_PATRON[claveDe(l)] = i + 1;
});

/** Numero King Wen (1..64) que corresponde a un patron de 6 lineas. */
export function numeroDeLineas(l: LineasHexagrama): number {
  return POR_PATRON[claveDe(l)];
}
